import { useEffect, useState } from 'react'
import { supabase } from '@/lib/supabase'
import { useToastStore } from '@/stores/toastStore'
import type { StaffInviteCode, UserRole } from '@/types/database'
import { ROLE_LABELS, formatDateTime } from '@/lib/format'
import { Card } from '@/components/ui/Card'
import { Button } from '@/components/ui/Button'
import { Badge } from '@/components/ui/Badge'
import { Input } from '@/components/ui/Input'
import { Select } from '@/components/ui/Select'
import { ResponsiveTable, TableRow } from '@/components/ui/Table'

// Roles a signup code can grant. Admin accounts are never created by a code.
const CODE_ROLES: UserRole[] = ['staff', 'sales_staff', 'production_supervisor', 'hr_officer']

function codeStatus(c: StaffInviteCode): { label: string; variant: 'success' | 'warning' | 'danger' | 'default' } {
  if (c.revoked) return { label: 'Revoked', variant: 'danger' }
  if (c.use_count >= c.max_uses) return { label: 'Used up', variant: 'default' }
  if (new Date(c.expires_at).getTime() <= Date.now()) return { label: 'Expired', variant: 'warning' }
  return { label: 'Active', variant: 'success' }
}

export function StaffInviteCodes() {
  const addToast = useToastStore((s) => s.addToast)
  const [codes, setCodes] = useState<StaffInviteCode[]>([])
  const [loading, setLoading] = useState(true)
  const [creating, setCreating] = useState(false)
  const [justCreated, setJustCreated] = useState<StaffInviteCode | null>(null)
  const [form, setForm] = useState({ role: 'staff' as UserRole, days: '7', uses: '1', note: '' })

  const fetchCodes = async () => {
    const { data, error } = await supabase
      .from('staff_invite_codes')
      .select('*, staff_invite_uses(used_at, profiles(full_name, email))')
      .order('created_at', { ascending: false })
      .limit(50)

    if (error) addToast(error.message, 'error')
    else setCodes((data as StaffInviteCode[]) || [])
    setLoading(false)
  }

  useEffect(() => {
    fetchCodes()
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  const copy = async (code: string) => {
    try {
      await navigator.clipboard.writeText(code)
      addToast('Code copied')
    } catch {
      addToast(`Copy this code: ${code}`, 'info')
    }
  }

  const generate = async (e: React.FormEvent) => {
    e.preventDefault()
    setCreating(true)

    // The code itself is generated by the database, not by this page.
    const { data, error } = await supabase
      .from('staff_invite_codes')
      .insert({
        role: form.role,
        max_uses: parseInt(form.uses, 10),
        expires_at: new Date(Date.now() + parseInt(form.days, 10) * 86400000).toISOString(),
        note: form.note.trim() || null,
      })
      .select('*')
      .single()

    setCreating(false)

    if (error) {
      addToast(error.message, 'error')
      return
    }

    setJustCreated(data as StaffInviteCode)
    setForm({ ...form, note: '' })
    fetchCodes()
  }

  const revoke = async (c: StaffInviteCode) => {
    if (!window.confirm(`Revoke code ${c.code}? It will stop working immediately.`)) return
    const { error } = await supabase.from('staff_invite_codes').update({ revoked: true }).eq('id', c.id)
    if (error) addToast(error.message, 'error')
    else {
      addToast('Code revoked')
      fetchCodes()
    }
  }

  const usedBy = (c: StaffInviteCode) =>
    (c.staff_invite_uses || [])
      .map((u) => u.profiles?.full_name || u.profiles?.email)
      .filter(Boolean)
      .join(', ')

  return (
    <Card title="Employee Signup Codes">
      <p className="mb-4 text-sm leading-relaxed text-slate-600">
        New employees must enter a code from this page to create an account, so strangers can't sign themselves up.
        Generate one, send it to the person, and it works only until it expires or is used up. The code decides the
        role the new account gets.
      </p>

      <form onSubmit={generate} className="grid grid-cols-1 gap-4 sm:grid-cols-2">
        <Select
          label="Role for this employee"
          value={form.role}
          onChange={(e) => setForm({ ...form, role: e.target.value as UserRole })}
        >
          {CODE_ROLES.map((r) => (
            <option key={r} value={r}>{ROLE_LABELS[r]}</option>
          ))}
        </Select>
        <Input
          label="Who is it for? (optional)"
          value={form.note}
          onChange={(e) => setForm({ ...form, note: e.target.value })}
          placeholder="e.g. Kofi, machine operator"
        />
        <Select label="Valid for" value={form.days} onChange={(e) => setForm({ ...form, days: e.target.value })}>
          <option value="1">1 day</option>
          <option value="3">3 days</option>
          <option value="7">7 days</option>
          <option value="30">30 days</option>
        </Select>
        <Select label="Number of uses" value={form.uses} onChange={(e) => setForm({ ...form, uses: e.target.value })}>
          <option value="1">1 person</option>
          <option value="2">2 people</option>
          <option value="5">5 people</option>
          <option value="10">10 people</option>
        </Select>
        <div className="sm:col-span-2">
          <Button type="submit" loading={creating}>Generate code</Button>
        </div>
      </form>

      {justCreated && (
        <div className="mt-5 rounded-xl border border-brand-200 bg-brand-50 p-4">
          <p className="text-xs font-semibold uppercase tracking-wide text-brand-700">New code — share it now</p>
          <div className="mt-2 flex flex-wrap items-center gap-3">
            <span className="font-mono text-2xl font-bold tracking-wider text-brand-900">{justCreated.code}</span>
            <Button type="button" variant="secondary" onClick={() => copy(justCreated.code)}>Copy</Button>
          </div>
          <p className="mt-2 text-xs text-brand-800">
            {ROLE_LABELS[justCreated.role]} · {justCreated.max_uses} use{justCreated.max_uses === 1 ? '' : 's'} · valid
            until {formatDateTime(justCreated.expires_at)}. The employee enters it on the sign-up page.
          </p>
        </div>
      )}

      <div className="mt-6">
        <ResponsiveTable
          headers={['Code', 'Role', 'For', 'Used', 'Expires', 'Status', 'Actions']}
          isEmpty={!loading && codes.length === 0}
          emptyMessage="No codes yet"
        >
          {codes.map((c) => {
            const status = codeStatus(c)
            const names = usedBy(c)
            return (
              <TableRow
                key={c.id}
                cells={[
                  <span className="font-mono font-semibold">{c.code}</span>,
                  ROLE_LABELS[c.role],
                  c.note || '—',
                  `${c.use_count}/${c.max_uses}${names ? ` · ${names}` : ''}`,
                  formatDateTime(c.expires_at),
                  <Badge variant={status.variant}>{status.label}</Badge>,
                  <div className="flex gap-2">
                    <Button variant="secondary" onClick={() => copy(c.code)}>Copy</Button>
                    {status.label === 'Active' && (
                      <Button variant="danger" onClick={() => revoke(c)}>Revoke</Button>
                    )}
                  </div>,
                ]}
                mobileCard={
                  <div className="space-y-2 text-sm">
                    <div className="flex items-center justify-between">
                      <span className="font-mono font-semibold">{c.code}</span>
                      <Badge variant={status.variant}>{status.label}</Badge>
                    </div>
                    <p className="text-xs text-slate-500">
                      {ROLE_LABELS[c.role]}
                      {c.note ? ` · ${c.note}` : ''} · used {c.use_count}/{c.max_uses}
                      {names ? ` (${names})` : ''}
                    </p>
                    <p className="text-xs text-slate-500">Expires {formatDateTime(c.expires_at)}</p>
                    <div className="flex gap-2">
                      <Button variant="secondary" className="flex-1" onClick={() => copy(c.code)}>Copy</Button>
                      {status.label === 'Active' && (
                        <Button variant="danger" className="flex-1" onClick={() => revoke(c)}>Revoke</Button>
                      )}
                    </div>
                  </div>
                }
              />
            )
          })}
        </ResponsiveTable>
      </div>
    </Card>
  )
}
